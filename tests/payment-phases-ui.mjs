import assert from 'node:assert/strict'
import { pathToFileURL } from 'node:url'
import { mkdir } from 'node:fs/promises'
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href)
await mkdir(process.env.UI_OUTPUT, { recursive: true })
const browser = await chromium.launch({ channel: 'chrome', headless: true })
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } })
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('http://127.0.0.1:4175/gastos?expense=e1')
  const progress = page.getByRole('progressbar', { name: 'Importe pagado de Segundo pago de carpintería' })
  assert.equal(await progress.getAttribute('aria-valuenow'), '25')
  await page.getByText('Fase pendiente 2: Durante la obra', { exact: true }).waitFor()
  await page.getByRole('button', { name: 'Gestionar pagos', exact: true }).click()
  await page.getByLabel('Importe fase 2 (€)', { exact: true }).fill('1')
  await page.getByRole('button', { name: 'Guardar gasto', exact: true }).click()
  await page.getByRole('alert').filter({ hasText: 'La suma de las fases' }).waitFor()
  await page.getByLabel('Importe fase 2 (€)', { exact: true }).fill('1000')
  await page.getByLabel('Fase 2 pagada', { exact: true }).check()
  assert.notEqual(await page.getByLabel('Fecha de pago fase 2', { exact: true }).inputValue(), '')
  assert.equal(await page.getByLabel('Cantidad pagada', { exact: true }).isDisabled(), true)
  await page.getByRole('button', { name: 'Guardar gasto', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  assert.equal(await progress.getAttribute('aria-valuenow'), '67')
  await page.getByText('Fase pendiente 3: Liquidación', { exact: true }).waitFor()
  await page.screenshot({ path: `${process.env.UI_OUTPUT}/pagos-por-fases.png` })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByText('Fase pendiente 3: Liquidación', { exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: `${process.env.UI_OUTPUT}/pagos-por-fases-movil.png` })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth))
  await page.getByRole('button', { name: 'Gestionar pagos', exact: true }).click()
  await page.getByLabel('Fase 2 pagada', { exact: true }).uncheck()
  await page.getByRole('button', { name: 'Guardar gasto', exact: true }).click()
  await page.getByRole('dialog').waitFor({ state: 'hidden' })
  assert.equal(await progress.getAttribute('aria-valuenow'), '25')
  assert.deepEqual(errors, [])
  console.log('PASS UI: fase actual, barra por importe, validación, registrar/corregir pago y móvil.')
} finally { await browser.close() }
